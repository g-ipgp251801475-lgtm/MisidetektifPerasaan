"""Register recordings only when the files exist; never emit broken audio URLs."""
from pathlib import Path
import json
root = Path(__file__).resolve().parent.parent
names = {
 'welcome':'welcome-briar-ms.mp3', 'level1':'briar-instruction-ms.mp3',
 'level2':'bramble-instruction-ms.mp3', 'correct':'correct-answer-ms.mp3',
 'retry':'try-again-ms.mp3', 'ambience':'forest-ambience.mp3',
 'correctSound':'correct-sound.mp3', 'wrongSound':'incorrect-sound.mp3',
 'key':'key-collection.mp3', 'chest':'treasure-opening.mp3', 'win':'mission-complete.mp3'
}
paths = {key:'assets/audio/'+name for key,name in names.items() if (root/'assets/audio'/name).is_file()}
(root/'audio-assets.js').write_text('// Generated by tools/configure-audio.py. Only existing recordings are referenced.\nwindow.GAME_AUDIO = '+json.dumps(paths,indent=2)+';\n')
(root/'assets/audio/AVAILABILITY.json').write_text(json.dumps([{'role':k,'filename':v,'available':k in paths} for k,v in names.items()],indent=2)+'\n')
print('Available recordings:',len(paths),'of',len(names))
