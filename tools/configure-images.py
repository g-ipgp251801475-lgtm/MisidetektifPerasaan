"""Select exact uploaded originals when available, without renaming/altering them.
Run from any directory after placing originals in assets/images/ or assets/.
No dependencies. Existing supplied artwork remains an explicit temporary fallback.
"""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
mapping = {
 'home': ('Cheerful Forest Adventure Trio(2).png','01_homepage_group_scene.png'),
 'briar': ('Screenshot 2026-11-06 192839.png','03_briar_character.png'),
 'bramble': ('Screenshot 2026-11-06 192945.png','04_bramble_character.png'),
 'vick': ('Screenshot 2026-11-06 193001.png','05_logger_vick_character.png'),
 'level1': ('Screenshot 2026-11-06 192815.png','02_forest_background.png'),
 'map': ('Screenshot 2026-11-06 192815.png','02_forest_background.png'),
 'alternative': ('Screenshot (310).png','02_forest_background.png'),
 'level2': ('Screenshot (312).png','06_user_original_forest_reference.png'),
 'correct': ('Screenshot (308).png','04_bramble_character.png'),
 'wrong': ('Screenshot (309).png','04_bramble_character.png'),
 'victory': ('Forest Friends Adventure Trio(1).png','01_homepage_group_scene.png')
}
paths, report = {}, []
for role, (filename, fallback) in mapping.items():
    match = next((p for p in (root/'assets/images'/filename,root/'assets'/filename) if p.is_file()),None)
    paths[role] = str((match or root/'assets'/fallback).relative_to(root))
    report.append({'role':role,'required':filename,'path':paths[role],'original_available':bool(match)})
(root/'image-map.js').write_text('// Generated by tools/configure-images.py; filenames preserved.\nwindow.GAME_IMAGES = '+json.dumps(paths,ensure_ascii=False,indent=2)+';\n')
(root/'assets/IMAGE-MAPPING.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
for item in report:print(item['role'], 'EXACT' if item['original_available'] else 'PENDING ORIGINAL', item['required'])
